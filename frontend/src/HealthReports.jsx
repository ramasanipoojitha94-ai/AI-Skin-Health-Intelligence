import { useCallback, useEffect, useMemo, useState } from "react";
import {
  FileText,
  Download,
  CalendarDays,
  Activity,
  RefreshCw,
  Search,
  ShieldCheck,
} from "lucide-react";
import { jsPDF } from "jspdf";
import { apiRequest } from "./api";
import "./HealthReports.css";

export default function HealthReports() {
  const [reports, setReports] = useState([]);
  const [filter, setFilter] = useState("All");
  const [search, setSearch] = useState("");
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  const loadReports = useCallback(async () => {
    try {
      setLoading(true);
      setError("");

      const data = await apiRequest("/reports/me");

      setReports(Array.isArray(data) ? data : []);
    } catch (err) {
      setError(err.message || "Unable to load your reports.");
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    loadReports();
  }, [loadReports]);

  const filteredReports = useMemo(() => {
    const query = search.trim().toLowerCase();

    return reports.filter((report) => {
      const matchesFilter =
        filter === "All" || report.analysis_type === filter;

      const matchesSearch =
        String(report.result || "").toLowerCase().includes(query) ||
        String(report.analysis_type || "").toLowerCase().includes(query);

      return matchesFilter && matchesSearch;
    });
  }, [reports, filter, search]);

  const createPDF = (pdf, report, index = 0) => {
    if (index > 0) pdf.addPage();

    const pageWidth = pdf.internal.pageSize.getWidth();
    const pageHeight = pdf.internal.pageSize.getHeight();
    const margin = 20;
    const contentWidth = pageWidth - margin * 2;
    let y = 25;

    pdf.setFillColor(18, 83, 76);
    pdf.rect(0, 0, pageWidth, 48, "F");

    pdf.setTextColor(255, 255, 255);
    pdf.setFont("helvetica", "bold");
    pdf.setFontSize(21);
    pdf.text("DERMALYTIX", margin, y);

    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(11);
    pdf.text("AI-POWERED SKIN HEALTH PLATFORM", margin, y + 12);

    y = 68;

    pdf.setTextColor(18, 63, 59);
    pdf.setFont("helvetica", "bold");
    pdf.setFontSize(17);
    pdf.text("SKIN HEALTH REPORT", margin, y);

    y += 17;

    pdf.setDrawColor(210, 225, 221);
    pdf.line(margin, y, pageWidth - margin, y);
    y += 15;

    const fields = [
      ["Report ID", String(report.id ?? "Not available")],
      ["Analysis Type", report.analysis_type || "Not available"],
      [
        "Analysis Date",
        report.created_at
          ? new Date(report.created_at).toLocaleString()
          : "Not available",
      ],
      ["Prediction", report.result || "Not available"],
      [
        "Confidence",
        report.confidence != null &&
        Number.isFinite(Number(report.confidence))
          ? `${Number(report.confidence).toFixed(2)}%`
          : "Not available",
      ],
    ];

    pdf.setFontSize(10);

    fields.forEach(([label, value]) => {
      const labelWidth = 38;
      const lines = pdf.splitTextToSize(
        String(value),
        contentWidth - labelWidth
      );

      if (y + Math.max(10, lines.length * 6) > pageHeight - 75) {
        pdf.addPage();
        y = 25;
      }

      pdf.setFont("helvetica", "bold");
      pdf.setTextColor(18, 63, 59);
      pdf.text(`${label}:`, margin, y);

      pdf.setFont("helvetica", "normal");
      pdf.setTextColor(70, 80, 80);
      pdf.text(lines, margin + labelWidth, y);

      y += Math.max(10, lines.length * 6 + 5);
    });

    y += 12;

    if (y + 55 > pageHeight - 20) {
      pdf.addPage();
      y = 25;
    }

    pdf.setFillColor(235, 246, 242);
    pdf.roundedRect(
      margin,
      y,
      contentWidth,
      43,
      3,
      3,
      "F"
    );

    pdf.setFont("helvetica", "bold");
    pdf.setFontSize(11);
    pdf.setTextColor(18, 83, 76);
    pdf.text("IMPORTANT MEDICAL DISCLAIMER", margin + 8, y + 12);

    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(9);
    pdf.setTextColor(65, 75, 75);

    const disclaimer = pdf.splitTextToSize(
      "This is an experimental AI-generated educational result. It is not a medical diagnosis or a substitute for professional medical advice. Please consult a qualified dermatologist.",
      contentWidth - 16
    );

    pdf.text(disclaimer, margin + 8, y + 22);

    pdf.setFontSize(9);
    pdf.setTextColor(120, 120, 120);
    pdf.text(
      "Generated by DermaLytix",
      margin,
      pageHeight - 12
    );
  };

  const downloadReport = (report) => {
    try {
      const pdf = new jsPDF();
      createPDF(pdf, report);
      pdf.save(`DermaLytix_Report_${report.id ?? "report"}.pdf`);
    } catch {
      setError("Unable to generate this PDF report.");
    }
  };

  const downloadAllReports = () => {
    if (filteredReports.length === 0) return;

    try {
      const pdf = new jsPDF();

      filteredReports.forEach((report, index) => {
        createPDF(pdf, report, index);
      });

      pdf.save("DermaLytix_All_Health_Reports.pdf");
    } catch {
      setError("Unable to generate the PDF reports.");
    }
  };

  const skinCount = reports.filter(
    (report) => report.analysis_type === "AI Skin Analysis"
  ).length;

  const acneCount = reports.filter(
    (report) => report.analysis_type === "Acne Severity Analysis"
  ).length;

  if (loading) {
    return (
      <section className="health-reports">
        <div className="reports-loading">
          <RefreshCw size={22} className="reports-spinner" />
          <p>Loading your health reports...</p>
        </div>
      </section>
    );
  }

  return (
    <section className="health-reports">
      <div className="reports-heading">
        <span>YOUR SKIN HEALTH RECORDS</span>
        <h2>Health Reports</h2>
        <p>View and download your previous AI skin analysis reports.</p>
      </div>

      <div className="reports-summary">
        <div>
          <FileText size={24} />
          <span>Total Reports</span>
          <strong>{reports.length}</strong>
        </div>

        <div>
          <Activity size={24} />
          <span>Skin Analyses</span>
          <strong>{skinCount}</strong>
        </div>

        <div>
          <ShieldCheck size={24} />
          <span>Acne Analyses</span>
          <strong>{acneCount}</strong>
        </div>
      </div>

      <div className="reports-toolbar">
        <div className="reports-search">
          <Search size={18} />
          <input
            type="search"
            placeholder="Search reports..."
            value={search}
            onChange={(event) => setSearch(event.target.value)}
            aria-label="Search reports"
          />
        </div>

        <select
          value={filter}
          onChange={(event) => setFilter(event.target.value)}
          aria-label="Filter reports"
        >
          <option value="All">All Reports</option>
          <option value="AI Skin Analysis">Skin Analysis</option>
          <option value="Acne Severity Analysis">Acne Analysis</option>
        </select>

        <button
          type="button"
          onClick={loadReports}
          disabled={loading}
        >
          <RefreshCw size={17} />
          Refresh
        </button>

        <button
          type="button"
          onClick={downloadAllReports}
          disabled={filteredReports.length === 0}
        >
          <Download size={17} />
          Download All PDF
        </button>
      </div>

      {error && (
        <div className="reports-error" role="alert">
          <p>{error}</p>
          <button type="button" onClick={loadReports}>
            Try again
          </button>
        </div>
      )}

      {filteredReports.length === 0 ? (
        <div className="reports-empty">
          <FileText size={50} />
          <h3>
            {reports.length === 0
              ? "No reports available"
              : "No matching reports"}
          </h3>
          <p>
            {reports.length === 0
              ? "Complete an AI skin analysis to see your reports here."
              : "Try changing your search or filter."}
          </p>
        </div>
      ) : (
        <div className="reports-list">
          {filteredReports.map((report) => (
            <article className="report-card" key={report.id}>
              <div className="report-icon">
                <FileText size={27} />
              </div>

              <div className="report-details">
                <h3>{report.analysis_type || "Skin Analysis"}</h3>

                <p className="report-result">
                  {report.result || "No prediction details available."}
                </p>

                <p>
                  <CalendarDays size={15} />
                  {report.created_at &&
                  !Number.isNaN(new Date(report.created_at).getTime())
                    ? new Date(report.created_at).toLocaleDateString()
                    : "Date unavailable"}
                </p>

                <p>
                  Confidence:{" "}
                  {report.confidence != null &&
                  Number.isFinite(Number(report.confidence))
                    ? `${Number(report.confidence).toFixed(2)}%`
                    : "Not available"}
                </p>
              </div>

              <button
                type="button"
                className="report-download"
                onClick={() => downloadReport(report)}
              >
                <Download size={17} />
                Download PDF
              </button>
            </article>
          ))}
        </div>
      )}

      <p className="reports-disclaimer">
        AI-generated results are for educational purposes only and are not a
        medical diagnosis.
      </p>
    </section>
  );
}